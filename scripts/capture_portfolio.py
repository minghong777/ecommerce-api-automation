"""Actual app captures plus a clearly labelled Google API read-back evidence view.

Start Streamlit on :8502. No credentials are used by this browser script.
The Sheets evidence must first be generated by scripts/verify_sheets.py.
"""
from datetime import datetime, timezone
import html
import json
from pathlib import Path
import re
import shutil
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'docs/portfolio/screenshots'
OUT.mkdir(parents=True, exist_ok=True)
EVIDENCE = ROOT / 'docs/portfolio/sheets-verification.json'


def evidence_html(data: dict) -> str:
    def table(headers, rows):
        return '<table><thead><tr>' + ''.join('<th>'+html.escape(str(v))+'</th>' for v in headers) + '</tr></thead><tbody>' + ''.join('<tr>'+''.join('<td>'+html.escape(str(v))+'</td>' for v in row)+'</tr>' for row in rows) + '</tbody></table>'
    result = '''<!doctype html><html><meta charset="utf-8"><title>Google Sheets API read-back verification</title><style>
    *{box-sizing:border-box}body{margin:0;padding:38px 48px;background:#f7f9fc;color:#162b45;font:16px Arial,sans-serif}
    .hero{background:#162b45;color:white;padding:26px 30px;border-radius:16px}.tag{color:#52d5c0;font-weight:bold;font-size:13px;letter-spacing:2px}
    h1{font-size:32px;margin:14px 0}p{line-height:1.5;color:#60748a}.hero p{color:#c5d7e6;margin-bottom:0}.cards{display:flex;gap:16px;margin:22px 0}.card{background:white;border:1px solid #dfe7ef;border-radius:12px;padding:20px;flex:1}.value{font-size:32px;font-weight:bold;margin-top:10px}h2{font-size:21px;margin:24px 0 12px}
    table{border-collapse:collapse;width:100%;background:white;font-size:13px}th,td{padding:11px 12px;border-bottom:1px solid #dfe7ef;text-align:left;white-space:nowrap}th{background:#e9f1f5}footer{font-size:13px;color:#60748a;margin-top:18px}.success{color:#087f72;font-weight:bold}.note{font-size:13px}
    </style><div class="hero"><div class="tag">GOOGLE SHEETS API · HISTORICAL VERIFIED READ-BACK</div><h1>One report snapshot. No duplicate orders.</h1><p>Independent portfolio project · DEMO / SYNTHETIC DATA<br>Dated API evidence, not a live connection or the Google Sheets editor.</p></div>'''
    metrics = [('Managed worksheets',len(data['worksheets'])),('Unique orders',data['unique_order_ids']),('Duplicate orders',data['duplicate_orders']),('Demo recognized sales','$'+format(float(data['summary']['net_sales']),',.2f'))]
    result += '<div class="cards">'+''.join('<div class="card">'+label+'<div class="value">'+str(value)+'</div></div>' for label,value in metrics)+'</div>'
    result += '<p class="success">Two real synchronizations completed · Exact cell comparison passed · Financial reconciliation passed</p>'
    result += table(['Managed worksheet','Data rows (excluding header)','Columns','Read-back result'],[[w['name'],w['data_rows'],w['columns'],'Exact match'] for w in data['worksheets']])
    orders = data['worksheets'][1]
    result += '<h2>Orders · actual read-back sample</h2>'+table(orders['headers'],orders['sample_rows'][:5])
    products = data['worksheets'][2]
    result += '<h2>Product sales · actual read-back sample</h2>'+table(products['headers'],products['sample_rows'][:5])
    result += '<footer>Verified at '+html.escape(data['verified_at'])+' · All target cells checked, samples shown above.<br>Other worksheets preserved. No spreadsheet IDs, account identities, tokens, or credentials are included.</footer></html>'
    return result


def main() -> None:
    evidence = json.loads(EVIDENCE.read_text())
    if not evidence.get('verified') or not evidence.get('idempotency', {}).get('passed'):
        raise RuntimeError('Real verified read-back and idempotency evidence are required.')
    evidence_page = ROOT / 'docs/portfolio/sheets-readback.html'
    evidence_page.write_text(evidence_html(evidence))
    captures = []
    with sync_playwright() as p:
        browser = p.chromium.launch(executable_path=shutil.which('google-chrome'), headless=True,
                                   chromium_sandbox=True, args=['--disable-dev-shm-usage'])
        page = browser.new_page(viewport={'width':1440, 'height':1280}, device_scale_factor=1)
        page.goto('http://127.0.0.1:8502')
        page.get_by_role('heading', name='Overview', exact=True).wait_for()

        def capture(filename):
            page.wait_for_timeout(700)
            assert page.locator('[data-testid=stException]').count() == 0
            page.mouse.move(1,1)
            page.screenshot(path=str(OUT / filename))
            captures.append(filename)

        def navigate(name):
            page.get_by_text(name, exact=True).first.click()
            page.get_by_role('heading', name=name, exact=True).wait_for()
            page.wait_for_timeout(400)
            page.evaluate("document.querySelector('[data-testid=stMain]').scrollTo(0,0)")

        page.locator('[data-testid=stMetricValue]').first.wait_for()
        capture('01-dashboard.png')
        navigate('Orders Explorer')
        page.locator('[data-testid=stDataFrame]').first.wait_for()
        capture('02-orders.png')
        navigate('Sales Analytics')
        page.set_viewport_size({'width':1440,'height':1600})
        page.get_by_role('heading', name='Sales Analytics', exact=True).evaluate(
            "e => { const main = document.querySelector('[data-testid=stMain]'); main.scrollTop += e.getBoundingClientRect().top - 90; }")
        capture('03-sales-analytics.png')
        page.set_viewport_size({'width':1440,'height':1280})
        navigate('Report Export')
        capture('04-report-export.png')
        navigate('API Connection / Data Source')
        page.get_by_role('button', name='Fetch products from DummyJSON', exact=True).click()
        page.get_by_text(re.compile(r'Loaded \d+ validated products\.')).wait_for(timeout=90000)
        api_count = page.locator('[data-testid=stMetricValue]').first.inner_text()
        capture('05-api-integration.png')
        page.goto(evidence_page.as_uri())
        page.get_by_role('heading', name='One report snapshot. No duplicate orders.').wait_for()
        capture('06-google-sheets-verification.png')
        browser.close()
    (ROOT / 'docs/portfolio/capture-report.json').write_text(json.dumps({
        'captured_at':datetime.now(timezone.utc).isoformat(), 'screenshots':captures,
        'actual_api_product_count':int(api_count),'sheets_evidence':'Verified actual API read-back, rendered as a labelled evidence view.',
        'disclosure':'DEMO / SYNTHETIC DATA'}, indent=2))
    print(json.dumps({'screenshots':len(captures),'api_products':api_count,'output':str(OUT)},indent=2))


if __name__ == '__main__':
    main()
